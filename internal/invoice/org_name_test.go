package invoice

import "testing"

func TestShortenBuyerName(t *testing.T) {
	cases := []struct {
		in, want string
	}{
		{`ООО "Ромашка"`, "Ромашка"},
		{`Общество с ограниченной ответственностью "ППС"`, "ППС"},
		{`Общество с ограниченной ответственностью Ромашка`, "Ромашка"},
		{`ИП Архипов Данила Николаевич`, "Архипов Данила Николаевич"},
		{`Индивидуальный предприниматель Иванов И.И.`, "Иванов И.И."},
		{`Индувидуальный предприниматель Петров П.П.`, "Петров П.П."},
		{`АО "Газпром"`, "Газпром"},
		{`Акционерное общество Север`, "Север"},
		{`ОАО "РЖД"`, "РЖД"},
		{`Муниципальное бюджетное учреждение "СБГ"`, "СБГ"},
		{`МУНИЦИПАЛЬНОЕ АВТОНОМНОЕ УЧРЕЖДЕНИЕ «Школа №1»`, "Школа №1"},
		{`КОМИТЕТ (МБУ "СБГ" л/с 123)`, `СБГ" л/с 123)`},
		{`ООО "ППС"ЛЕССТР"`, `ППС"ЛЕССТР`},
		{`МБУ "СБГ`, "СБГ"},
		{`Просто Покупатель`, "Просто Покупатель"},
		{"", ""},
	}
	for _, tc := range cases {
		if got := ShortenBuyerName(tc.in); got != tc.want {
			t.Fatalf("%q: got %q want %q", tc.in, got, tc.want)
		}
	}
}
